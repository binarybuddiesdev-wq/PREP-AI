export const PISTON_CONTAINER_NAME = 'piston_api';

export const buildPistonContainerArgs = (entrypointPath: string): string[] => {
  const normalizedPath = entrypointPath.replace(/\\/g, '/');

  return [
    'run',
    '-d',
    '--name',
    PISTON_CONTAINER_NAME,
    '-p',
    '127.0.0.1:2000:2000',
    '--privileged',
    '--cpus=4',
    '--memory=2g',
    '--pids-limit=512',
    '--env',
    'PISTON_DISABLE_NETWORKING=true',
    '--env',
    'PISTON_MAX_PROCESS_COUNT=32',
    '--env',
    'PISTON_MAX_OPEN_FILES=64',
    '--env',
    'PISTON_MAX_FILE_SIZE=1048576',
    '--env',
    'PISTON_OUTPUT_MAX_SIZE=16384',
    '--env',
    'PISTON_MAX_CONCURRENT_JOBS=5',
    '--env',
    'PISTON_COMPILE_TIMEOUT=10000',
    '--env',
    'PISTON_RUN_TIMEOUT=3000',
    '--env',
    'PISTON_COMPILE_CPU_TIME=10000',
    '--env',
    'PISTON_RUN_CPU_TIME=3000',
    '--env',
    'PISTON_COMPILE_MEMORY_LIMIT=268435456',
    '--env',
    'PISTON_RUN_MEMORY_LIMIT=268435456',
    '--add-host',
    'release-assets.githubusercontent.com:185.199.108.133',
    '--add-host',
    'objects.githubusercontent.com:185.199.108.133',
    '--add-host',
    'raw.githubusercontent.com:185.199.108.133',
    '-v',
    'piston_data:/piston',
    '-v',
    `"${normalizedPath}:/piston_api/src/docker-entrypoint.sh:ro"`,
    'ghcr.io/engineer-man/piston',
  ];
};
