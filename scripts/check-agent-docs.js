#!/usr/bin/env node
// Guards the instruction files (CLAUDE.md files, agents, skills) against silent rot.
// Three things go wrong without it:
//   - a skill or agent cites a path or a skill that no longer exists, so the reader is sent nowhere;
//   - the CLAUDE.md skill list and the skills on disk drift apart after a move or a rename;
//   - an unquoted `: ` in YAML frontmatter makes the skill or agent silently drop out of the roster.
//
// Usage: node scripts/check-agent-docs.js [--root <dir>]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootArgIndex = process.argv.indexOf('--root');
const repoRoot = path.resolve(
  rootArgIndex > -1 ? process.argv[rootArgIndex + 1] : path.join(scriptDir, '..')
);

const SKILL_SCOPES = ['.claude/skills', 'server/.claude/skills', 'ui/.claude/skills'];
const AGENT_DIR = '.claude/agents';
const PATH_ROOTS = [
  'server/',
  'ui/',
  'docs/',
  'routes/',
  'scripts/',
  '.claude/',
  '.github/',
  '.husky/',
  'e2e/',
  'types/',
];
const DESCRIPTION_MAX_LENGTH = 1024;

// Paths that are generated, not yet created, or deliberately illustrative. Each needs a reason.
const ALLOWED_MISSING = [
  [/^server\/src\/generated(\/|$)/, 'generated by `pnpm prisma:generate`, gitignored'],
  [
    /^server\/prisma\/migrations(\/|$)/,
    'no migration history exists yet; db-schema-change explains',
  ],
  [/^server\/test\/e2e(\/|$)/, 'no server e2e files exist yet; testing explains'],
  [/^server\/dist(\/|$)/, 'build output'],
  [
    /^ui\/pnpm-workspace\.yaml$/,
    'untracked placeholder pnpm may create; ui-verify-implementation explains',
  ],
  [
    /^ui\/src\/(components\/(hello|bye)|pages\/dashboard|data|logic|service|core|utils)(\/|$)/,
    'illustrative or 7-layer target folders that do not exist yet',
  ],
  [
    /^server\/src\/modules\/(coding|<name>)(\/|$)/,
    'illustrative module name in the api-design examples',
  ],
  [/^routes\/coding-api-spec\.md$/, 'illustrative spec name in the api-design examples'],
  [/^docs\/adr\/NNNN-/, 'illustrative ADR file name in the architect template instructions'],
];

const errors = [];
const fail = (file, message) =>
  errors.push(`${path.relative(repoRoot, file).split(path.sep).join('/')}: ${message}`);
const exists = (relative) => fs.existsSync(path.join(repoRoot, relative));
const read = (file) => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');

const parseFrontmatter = (text) => {
  const match = text.match(/^---\n([\s\S]*?)\n---/);
  if (!match) {
    return null;
  }
  const fields = {};
  for (const line of match[1].split('\n')) {
    const pair = line.match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (pair) {
      fields[pair[1]] = pair[2].trim();
    }
  }
  return fields;
};

const unquote = (value) => value.replace(/^(["'])([\s\S]*)\1$/, '$2');

const checkFrontmatter = (file, expectedName, kind) => {
  const fields = parseFrontmatter(read(file));
  if (!fields) {
    fail(file, 'no frontmatter block');
    return null;
  }
  for (const key of ['name', 'description']) {
    if (!fields[key]) {
      fail(file, `frontmatter is missing \`${key}\``);
    }
  }
  for (const [key, value] of Object.entries(fields)) {
    if (!/^["']/.test(value) && /: /.test(value)) {
      fail(
        file,
        `unquoted ': ' in \`${key}\` (YAML reads a nested mapping and the ${kind} drops out of the roster)`
      );
    }
  }
  if (fields.name && fields.name !== expectedName) {
    fail(
      file,
      `name \`${fields.name}\` does not match its ${kind === 'skill' ? 'folder' : 'file'} \`${expectedName}\``
    );
  }
  if (fields.description && unquote(fields.description).length > DESCRIPTION_MAX_LENGTH) {
    fail(file, `description is longer than ${DESCRIPTION_MAX_LENGTH} characters`);
  }
  return fields;
};

// Discover skills and agents.
const skills = []; // { name, dir, file, scope }
for (const scope of SKILL_SCOPES) {
  const scopeDir = path.join(repoRoot, scope);
  if (!fs.existsSync(scopeDir)) {
    continue;
  }
  for (const entry of fs.readdirSync(scopeDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) {
      continue;
    }
    const file = path.join(scopeDir, entry.name, 'SKILL.md');
    if (!fs.existsSync(file)) {
      fail(path.join(scopeDir, entry.name), 'skill folder has no SKILL.md');
      continue;
    }
    skills.push({ name: entry.name, dir: path.join(scopeDir, entry.name), file, scope });
  }
}

const agents = []; // { name, file, fields }
const agentDir = path.join(repoRoot, AGENT_DIR);
if (fs.existsSync(agentDir)) {
  for (const entry of fs.readdirSync(agentDir)) {
    if (entry.endsWith('.md')) {
      const file = path.join(agentDir, entry);
      const name = entry.replace(/\.md$/, '');
      agents.push({ name, file, fields: checkFrontmatter(file, name, 'agent') });
    }
  }
}

const seenSkillNames = new Map();
for (const skill of skills) {
  checkFrontmatter(skill.file, skill.name, 'skill');
  if (seenSkillNames.has(skill.name)) {
    fail(
      skill.file,
      `skill name \`${skill.name}\` is also defined in ${seenSkillNames.get(skill.name)}`
    );
  }
  seenSkillNames.set(skill.name, path.relative(repoRoot, skill.file).split(path.sep).join('/'));
}
const skillNames = new Set(skills.map((skill) => skill.name));
const agentNames = new Set(agents.map((agent) => agent.name));

// The root CLAUDE.md skill list must match the skills on disk.
const claudeFile = path.join(repoRoot, 'CLAUDE.md');
const claudeText = fs.existsSync(claudeFile) ? read(claudeFile) : '';
const listedSkills = new Map();
for (const match of claudeText.matchAll(/\[`([a-z0-9-]+)`\]\(([^)]*SKILL\.md)\)/g)) {
  listedSkills.set(match[1], match[2]);
}
for (const [name, target] of listedSkills) {
  const skill = skills.find((candidate) => candidate.name === name);
  if (!skill) {
    fail(claudeFile, `lists skill \`${name}\` but no such skill exists on disk`);
  } else if (path.resolve(path.dirname(claudeFile), target) !== skill.file) {
    fail(
      claudeFile,
      `skill \`${name}\` links to \`${target}\` but lives at ${path.relative(repoRoot, skill.file).split(path.sep).join('/')}`
    );
  }
}
for (const skill of skills) {
  if (!listedSkills.has(skill.name)) {
    fail(
      claudeFile,
      `skill \`${skill.name}\` exists on disk but is not listed in the Agent Skills section`
    );
  }
}
const agentsParagraph = (claudeText.match(/\*\*Agents\*\*[\s\S]*?(?=\n\n|$)/) || [''])[0];
for (const agent of agents) {
  if (!agentsParagraph.includes(`\`${agent.name}\``)) {
    fail(
      claudeFile,
      `agent \`${agent.name}\` exists on disk but is not named in the Agents paragraph`
    );
  }
}
for (const match of agentsParagraph.matchAll(/`([a-z-]+)`/g)) {
  if (!agentNames.has(match[1])) {
    fail(claudeFile, `Agents paragraph names \`${match[1]}\` but no such agent exists`);
  }
}

// Every nested CLAUDE.md should name skills that exist.
const claudeFiles = [
  claudeFile,
  path.join(repoRoot, 'server/CLAUDE.md'),
  path.join(repoRoot, 'ui/CLAUDE.md'),
].filter((file) => fs.existsSync(file));

// Cited paths, links and skill names in every instruction file.
const stripFences = (text) => text.replace(/```[\s\S]*?```/g, '');
const docFiles = [
  ...claudeFiles,
  ...agents.map((agent) => agent.file),
  ...skills.flatMap((skill) => collectMarkdown(skill.dir)),
];

function collectMarkdown(dir) {
  const found = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      found.push(...collectMarkdown(entryPath));
    } else if (entry.name.endsWith('.md')) {
      found.push(entryPath);
    }
  }
  return found;
}

const isAllowedMissing = (relative) => ALLOWED_MISSING.some(([pattern]) => pattern.test(relative));
const LINE_ANCHOR = /(:\d+(-\d+)?|#L\d+(-L?\d+)?|#[\w-]+)$/;

for (const file of new Set(docFiles)) {
  const text = stripFences(read(file));

  for (const match of text.matchAll(/`([^`\n]+)`/g)) {
    let token = match[1].trim().replace(LINE_ANCHOR, '');
    if (/[<>*{}$|\s]/.test(token) || !PATH_ROOTS.some((root) => token.startsWith(root))) {
      continue;
    }
    token = token.replace(/\/$/, '');
    if (!exists(token) && !isAllowedMissing(token)) {
      fail(file, `cites \`${token}\` which does not exist`);
    }
  }

  for (const match of text.matchAll(/\]\(([^)\s]+)\)/g)) {
    const target = match[1].split('#')[0];
    if (!target || /^[a-z]+:/i.test(target) || target.startsWith('mailto:')) {
      continue;
    }
    const resolved = path.resolve(path.dirname(file), target);
    const relative = path.relative(repoRoot, resolved).split(path.sep).join('/');
    if (!fs.existsSync(resolved) && !isAllowedMissing(relative)) {
      fail(file, `links to \`${target}\` which does not resolve`);
    }
  }

  for (const match of text.matchAll(
    /((?:`[a-z0-9-]+`(?:,\s+|\s+and\s+|\s+or\s+)?)+)\s+skills?\b/g
  )) {
    for (const nameMatch of match[1].matchAll(/`([a-z0-9-]+)`/g)) {
      if (!skillNames.has(nameMatch[1])) {
        fail(file, `refers to skill \`${nameMatch[1]}\` which does not exist`);
      }
    }
  }
}

// An agent that tells itself to use the Skill tool must be allowed to.
for (const agent of agents) {
  const text = read(agent.file);
  const tools = agent.fields?.tools || '';
  if (/`Skill`\s+tool|Skill tool/.test(text) && !/\bSkill\b/.test(tools)) {
    fail(agent.file, 'tells the agent to use the Skill tool but `tools:` does not list `Skill`');
  }
}

if (errors.length > 0) {
  console.error(`check-agent-docs: ${errors.length} problem(s)\n`);
  for (const error of errors) {
    console.error(`  - ${error}`);
  }
  process.exit(1);
}
console.info(
  `check-agent-docs: ok (${skills.length} skills, ${agents.length} agents, ${claudeFiles.length} CLAUDE.md files)`
);
